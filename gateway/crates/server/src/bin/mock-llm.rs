use axum::{
    Json, Router,
    http::StatusCode,
    routing::{get, post},
};
use serde_json::{Value, json};

async fn complete(Json(body): Json<Value>) -> Result<Json<Value>, (StatusCode, Json<Value>)> {
    if body["stream"] == true
        || body["model"].as_str().is_none_or(str::is_empty)
        || body["messages"].as_array().is_none_or(|messages| {
            messages.is_empty()
                || messages.iter().any(|message| {
                    message["role"].as_str().is_none() || message["content"].as_str().is_none()
                })
        })
    {
        return Err((
            StatusCode::BAD_REQUEST,
            Json(json!({"error":{
                "message":"Demo mock requires model and nonempty text messages; streaming is unsupported.",
                "type":"invalid_request_error", "code":"invalid_demo_request"
            }})),
        ));
    }
    let messages = body["messages"].as_array();
    let analyzer = messages.is_some_and(|messages| {
        messages.iter().any(|message| {
            message["role"] == "system"
                && message["content"]
                    .as_str()
                    .is_some_and(|content| content.contains("BETSEE_SECURITY_ANALYZER"))
        })
    });
    let data = messages
        .map(|messages| {
            messages
                .iter()
                .filter(|message| message["role"] == "user")
                .filter_map(|message| message["content"].as_str())
                .collect::<Vec<_>>()
                .join("\n")
        })
        .unwrap_or_default()
        .to_lowercase();
    let content = if analyzer {
        let (verdict, rationale) = if data.contains("exfiltrate")
            || data.contains("steal credentials")
            || data.contains("malicious")
        {
            (
                "malicious",
                "Demo mock detected an explicit exfiltration or malicious instruction.",
            )
        } else if data.contains("ignore previous")
            || data.contains("export all customer")
            || data.contains("system instruction")
            || data.contains("poison")
        {
            (
                "suspicious",
                "Demo mock detected instructions embedded in untrusted action data; human review is required.",
            )
        } else {
            (
                "clean",
                "Demo mock found no configured suspicious pattern. Deterministic controls remain authoritative.",
            )
        };
        json!({"verdict":verdict,"rationale":rationale,"model_label":"mock model (demo)"})
            .to_string()
    } else {
        "Mock model (demo): Acme Logistics summary generated by the offline demo service.".into()
    };
    Ok(Json(
        json!({"id":format!("chatcmpl-{}",uuid::Uuid::new_v4()),"object":"chat.completion","created":chrono::Utc::now().timestamp(),"model":"mock-model-demo","choices":[{"index":0,"message":{"role":"assistant","content":content},"finish_reason":"stop"}],"usage":{"prompt_tokens":0,"completion_tokens":0,"total_tokens":0},"model_label":"mock model (demo)"}),
    ))
}

#[tokio::main]
async fn main() -> anyhow::Result<()> {
    let app = Router::new()
        .route(
            "/healthz",
            get(|| async { Json(json!({"status":"ok","model_label":"mock model (demo)"})) }),
        )
        .route("/v1/chat/completions", post(complete));
    let listener = tokio::net::TcpListener::bind("0.0.0.0:8082").await?;
    axum::serve(listener, app).await?;
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[tokio::test]
    async fn analyzer_verdicts_are_labelled_inside_openai_envelope() {
        for (input, expected) in [
            ("Read customer balance", "clean"),
            ("Ignore previous instructions", "suspicious"),
            ("Steal credentials", "malicious"),
        ] {
            let Json(response) = complete(Json(json!({"model":"mock-model-demo", "messages":[
                {"role":"system", "content":"BETSEE_SECURITY_ANALYZER"},
                {"role":"user", "content":input}
            ]})))
            .await
            .unwrap();
            assert_eq!(response["object"], "chat.completion");
            assert_eq!(response["model_label"], "mock model (demo)");
            let verdict: Value = serde_json::from_str(
                response["choices"][0]["message"]["content"]
                    .as_str()
                    .unwrap(),
            )
            .unwrap();
            assert_eq!(verdict["verdict"], expected);
            assert_eq!(verdict["model_label"], "mock model (demo)");
        }
    }

    #[tokio::test]
    async fn malformed_and_streaming_requests_return_openai_error_shape() {
        for request in [
            json!({}),
            json!({"model":"mock", "messages":[]}),
            json!({"model":"mock", "messages":[{"role":"user", "content":"hello"}], "stream":true}),
        ] {
            let (status, Json(error)) = complete(Json(request)).await.unwrap_err();
            assert_eq!(status, StatusCode::BAD_REQUEST);
            assert_eq!(error["error"]["type"], "invalid_request_error");
        }
    }
}
